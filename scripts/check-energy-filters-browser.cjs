// Usage: node scripts/check-energy-filters-browser.cjs <playwright-package-path> [base-url]
const assert = require('node:assert/strict');
const XLSX = require('xlsx');
const { chromium } = require(process.argv[2] || 'playwright');
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    const base = process.argv[3] || 'http://localhost:3000';
    const workbook = XLSX.readFile('data/CGC_Energy_2026_Mock_Only.xlsx');
    const rows = XLSX.utils.sheet_to_json(workbook.Sheets.Energy_Data_2026_Mock, { range: 2 });
    const expected = rows.filter(row => ['F04', 'F05'].includes(row.Floor_ID) && [7, 8, 9].includes(XLSX.SSF.parse_date_code(row.Month).m)).reduce((sum, row) => sum + row.Electricity_kWh, 0);
    await page.goto(base + '/?keep=1&year=2026&startMonth=6&endMonth=8&floors=F04,F05', { waitUntil: 'networkidle' });
    await page.getByText(expected.toLocaleString('en-US') + ' kWh', { exact: true }).waitFor();
    assert.equal(await page.getByRole('img', { name: /monthly electricity:/ }).count(), 1);
    assert.match(await page.locator('table').filter({ has: page.locator('caption', { hasText: /monthly electricity:/ }) }).textContent(), /Jul.*Aug.*Sep/s);
    const insightsLink = page.getByRole('link', { name: 'Insights', exact: true });
    const href = await insightsLink.getAttribute('href');
    assert.ok(!new URL(href, base).searchParams.has('floors'));
    await insightsLink.click(); await page.getByText(/supports one floor at a time/).waitFor();
    await page.getByRole('button', { name: /Analysis Period: July/ }).waitFor();
    await page.getByRole('button', { name: 'Floor: All Floors', exact: true }).click();
    await page.getByRole('dialog', { name: 'Floor', exact: true }).getByRole('button', { name: 'Floor 4', exact: true }).click();
    await page.waitForURL(/floors=F04/);
    await page.reload({ waitUntil: 'networkidle' }); await page.getByRole('button', { name: 'Floor: Floor 4', exact: true }).waitFor();
    await page.getByRole('link', { name: 'Savings & Cost', exact: true }).click();
    await page.getByRole('button', { name: /Analysis Period: July/ }).waitFor();
    assert.equal(new URL(page.url()).searchParams.get('floors'), 'F04');
    await page.goto(base + '/', { waitUntil: 'networkidle' });
    const floorTrigger = page.getByRole('button', { name: 'Floor: All Floors', exact: true });
    await floorTrigger.click();
    const picker = page.getByRole('dialog', { name: 'Floor', exact: true });
    await picker.getByRole('button', { name: 'Clear', exact: true }).click();
    await picker.getByRole('checkbox', { name: 'Floor 4', exact: true }).check();
    await picker.getByRole('button', { name: 'Cancel', exact: true }).click();
    assert.equal(new URL(page.url()).searchParams.has('floors'), false);
    await floorTrigger.click(); await picker.getByRole('button', { name: 'Clear', exact: true }).click();
    await picker.getByRole('checkbox', { name: 'Floor 4', exact: true }).check();
    await picker.getByRole('checkbox', { name: 'Floor 5', exact: true }).check();
    await picker.getByRole('button', { name: 'Apply', exact: true }).click(); await page.waitForURL(/floors=F04%2CF05/);
    await page.getByRole('button', { name: /^Filters/ }).click();
    await page.getByRole('combobox', { name: 'Floor performance sort', exact: true }).selectOption('usage');
    assert.equal(await page.getByRole('button', { name: 'Remove Floor performance sort filter' }).count(), 0);
    await page.getByRole('button', { name: 'Apply filters', exact: true }).click();
    await page.getByRole('button', { name: 'Remove Floor performance sort filter' }).waitFor();
    await page.getByRole('button', { name: /^Filters/ }).click();
    await page.getByRole('button', { name: 'Reset', exact: true }).click();
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: 'Remove Floor performance sort filter' }).count(), 1, 'Cancel discards advanced Reset draft');
    await page.getByRole('button', { name: /^Filters/ }).click();
    await page.getByRole('button', { name: 'Reset', exact: true }).click();
    await page.getByRole('button', { name: 'Apply filters', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: 'Remove Floor performance sort filter' }).count(), 0);
    assert.equal(new URL(page.url()).searchParams.get('floors'), 'F04,F05', 'Advanced Reset preserves common scope');
    await page.getByRole('button', { name: 'Clear all', exact: true }).click();
    await page.waitForURL(url => !url.searchParams.has('floors'));
    assert.equal(await page.getByRole('button', { name: 'Remove Floor performance sort filter' }).count(), 0);
    await page.goto(base + '/insights?year=2026&startMonth=0&endMonth=11', { waitUntil: 'networkidle' });
    await page.getByRole('button', { name: 'Anomalies', exact: true }).click();
    await page.getByRole('button', { name: /^Filters/ }).click();
    await page.getByRole('combobox', { name: 'Anomaly severity', exact: true }).selectOption('high');
    assert.equal(await page.getByRole('heading', { name: 'Unexpected Usage Drop', exact: true }).count(), 1);
    await page.getByRole('button', { name: 'Apply filters', exact: true }).click();
    assert.equal(await page.getByRole('heading', { name: 'Unexpected Usage Drop', exact: true }).count(), 0);
    await page.getByRole('heading', { name: 'High Consumption / Cooling Load', exact: true }).waitFor();
    await page.goto(base + '/report-energy-waste?year=2026&startMonth=8&endMonth=8&floors=F04', { waitUntil: 'networkidle' });
    await page.getByRole('cell', { name: /Floor 4/ }).waitFor();
    await page.getByRole('button', { name: /^Filters/ }).click();
    await page.getByRole('combobox', { name: 'Issue type', exact: true }).selectOption('Lights');
    await page.getByRole('button', { name: 'Apply filters', exact: true }).click(); await page.getByText('No reports in this view', { exact: true }).waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: /Analysis Period:/ }).click();
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('dialog', { name: 'Analysis Period' }).count(), 0);
    await page.getByRole('button', { name: /Floor:/ }).focus();
    await page.keyboard.press('ArrowDown');
    await page.getByRole('dialog', { name: 'Floor', exact: true }).waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('button', { name: /Floor:/ }).evaluate(node => node === document.activeElement), true);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.deepEqual(errors, []);
    console.log('Shared filters: range totals, URL persistence, safe navigation, draft Apply/Cancel, chips, advanced filters, report scope and mobile keyboard passed.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
